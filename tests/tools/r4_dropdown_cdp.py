"""R4-1 Dropdown — real keyboard / mouse / touch / accessibility audit via CDP. Run from project root."""
import sys, time, os
sys.dont_write_bytecode = True; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cdp_lib import Harness
H = Harness()
ok, ev, key = H.ok, H.ev, H.key
H.navigate("tests/fixtures/r4-dropdown-interaction.html")
ok("loads without errors", not H.problems(), H.problems())
ok("initDropdowns exported", ev("import('/src/annachy.js').then(m => typeof m.initDropdowns)") == "function")
isopen = lambda m: ev(f"!document.getElementById('{m}').hidden")
attr = lambda i, a: ev(f"document.getElementById('{i}').getAttribute('{a}')")
sel = lambda lst: ev(f"[...document.querySelectorAll('#{lst} [aria-selected=\"true\"]')].map(o => o.id).join()")
def tab_to(i):
    for _ in range(25):
        if H.active() == i: return True
        key("Tab")
    return H.active() == i
ok("menus closed on load", not any(ev(f"!document.getElementById('{m}').hidden") for m in ("single-menu", "multi-menu", "search-menu", "dis-menu", "bottom-menu")))

# ------------------------------------------------ Single (select-only combobox)
ok("tab reaches single trigger", tab_to("single-trigger"))
key("Enter"); ok("Enter opens", isopen("single-menu") and attr("single-trigger", "aria-expanded") == "true")
ok("focus stays on trigger", H.active() == "single-trigger")
ok("active = selected option on open", attr("single-trigger", "aria-activedescendant") == "s-1")
ok("active option shows Figma Focus treatment", "inset" in ev("getComputedStyle(document.getElementById('s-1')).boxShadow"))
key("ArrowDown"); ok("ArrowDown → next", attr("single-trigger", "aria-activedescendant") == "s-2")
key("ArrowDown"); key("ArrowDown"); ok("disabled option reachable (R4-Q2)", attr("single-trigger", "aria-activedescendant") == "s-4")
key("Enter"); ok("Enter on disabled does not select (stays open)", sel("single-list") == "s-1" and isopen("single-menu"))
key("End"); ok("End → last", attr("single-trigger", "aria-activedescendant") == "s-5")
key("ArrowDown"); ok("no wrap at end", attr("single-trigger", "aria-activedescendant") == "s-5")
key("Home"); ok("Home → first", attr("single-trigger", "aria-activedescendant") == "s-1")
key("f"); ok("typeahead 'f' → Finance (first f after current)", attr("single-trigger", "aria-activedescendant") == "s-4")
key("f"); ok("repeated 'f' cycles → Facilities", attr("single-trigger", "aria-activedescendant") == "s-5")
time.sleep(0.6); key("c"); key("u"); ok("typeahead string 'cu' → Customer success (500 ms buffer)", attr("single-trigger", "aria-activedescendant") == "s-3")
time.sleep(0.6); key("e"); ok("buffer resets after 500 ms ('e' → Engineering)", attr("single-trigger", "aria-activedescendant") == "s-2")
key("Enter")
ok("Enter selects and closes", sel("single-list") == "s-2" and not isopen("single-menu"))
ok("focus restored to trigger", H.active() == "single-trigger")
ok("annachy-change single", ev("JSON.stringify(window.__changes.at(-1))") == '["dd-single","eng"]')
key(" "); ok("Space opens", isopen("single-menu") and attr("single-trigger", "aria-activedescendant") == "s-2")
key("Escape"); ok("Escape closes, focus trigger, selection unchanged", not isopen("single-menu") and H.active() == "single-trigger" and sel("single-list") == "s-2")
ok("activedescendant cleared on close", attr("single-trigger", "aria-activedescendant") is None)
key("ArrowUp"); ok("ArrowUp opens (selected active)", isopen("single-menu") and attr("single-trigger", "aria-activedescendant") == "s-2")
key("Tab"); ok("Tab closes and moves on", not isopen("single-menu") and H.active() == "multi-trigger")
# mouse
H.click("#single-trigger"); ok("click opens", isopen("single-menu"))
H.hover("#s-3"); ok("hover fill Background/Tertiary", ev("getComputedStyle(document.getElementById('s-3')).backgroundColor") == "rgb(237, 239, 242)")
ok("hover does not move activedescendant (S11)", attr("single-trigger", "aria-activedescendant") == "s-2")
H.click("#s-4"); ok("click on disabled option ignored", sel("single-list") == "s-2" and isopen("single-menu"))
H.click("#s-3"); ok("click selects + closes", sel("single-list") == "s-3" and not isopen("single-menu"))
H.click("#single-trigger"); H.click("#before"); ok("outside click closes (focus goes to clicked element)", not isopen("single-menu") and H.active() == "before")
# touch
H.call("Emulation.setTouchEmulationEnabled", enabled=True, maxTouchPoints=1)
H.tap("#single-trigger"); ok("tap opens", isopen("single-menu"))
H.tap("#s-1"); ok("tap selects + closes", sel("single-list") == "s-1" and not isopen("single-menu"))
H.call("Emulation.setTouchEmulationEnabled", enabled=False)

# ------------------------------------------------ Multiple
ok("tab reaches multi trigger", tab_to("multi-trigger"))
key("ArrowDown"); ok("ArrowDown opens multi (first selected active)", isopen("multi-menu") and attr("multi-trigger", "aria-activedescendant") == "m-1")
key("ArrowDown"); key("ArrowDown"); key(" ")
ok("Space toggles m-3 on, stays open", sel("multi-list") == "m-1,m-2,m-3" and isopen("multi-menu"))
time.sleep(0.1); ok("polite announcement '3 selected' (R4-Q6)", ev("document.querySelector('#multi-menu [role=status]').textContent").strip() == "3 selected")
ok("status region polite", ev("document.querySelector('#multi-menu [role=status]').getAttribute('aria-live')") == "polite")
key("Home"); key("Enter"); ok("Enter toggles m-1 off", sel("multi-list") == "m-2,m-3")
time.sleep(0.1); ok("announcement '2 selected'", ev("document.querySelector('#multi-menu [role=status]').textContent").strip() == "2 selected")
ok("annachy-change multiple", ev("JSON.stringify(window.__changes.at(-1))") == '["dd-multi","eng,cs"]')
key("End"); key(" "); ok("disabled option not toggled", sel("multi-list") == "m-2,m-3")
H.click("#m-1"); ok("click toggles, stays open", sel("multi-list") == "m-1,m-2,m-3" and isopen("multi-menu"))
ok("selected multiple fill + indicator colour", ev("getComputedStyle(document.getElementById('m-1')).backgroundColor + '|' + getComputedStyle(document.querySelector('#m-1 .annachy-dropdown-item__indicator')).color") == "rgb(243, 247, 255)|rgb(0, 79, 235)")
key("Escape"); ok("Escape closes multi", not isopen("multi-menu"))

# ------------------------------------------------ Searchable (dialog + search combobox)
ok("tab reaches search trigger", tab_to("search-trigger"))
key("Enter"); ok("Enter opens dialog, focus in search", isopen("search-menu") and H.active() == "search-input")
ok("no active option on open", attr("search-input", "aria-activedescendant") is None)
ok("search combobox expanded", attr("search-input", "aria-expanded") == "true")
H.type("en")
ok("filter: only Engineering visible", ev("[...document.querySelectorAll('#search-list [role=option]')].filter(o => !o.hidden).map(o => o.id).join()") == "q-2")
time.sleep(1.0); ok("polite results announcement after 500 ms", ev("document.querySelector('#search-menu [role=status]').textContent").strip() == "1 results")
key("g"); time.sleep(1.0)
ok("identical consecutive result count re-announced (text changes)", ev("document.querySelector('#search-menu [role=status]').textContent") == "1 results ", repr(ev("document.querySelector('#search-menu [role=status]').textContent")))
key("Backspace")
key("ArrowDown"); ok("ArrowDown → first visible", attr("search-input", "aria-activedescendant") == "q-2")
key("Home"); ok("Home moves caret, not option", attr("search-input", "aria-activedescendant") == "q-2" and ev("document.getElementById('search-input').selectionStart") == 0)
key("Enter"); ok("Enter selects + closes + focus trigger", sel("search-list") == "q-2" and not isopen("search-menu") and H.active() == "search-trigger")
key("Enter"); ok("reopen resets search and filter", ev("document.getElementById('search-input').value") == "" and ev("[...document.querySelectorAll('#search-list [role=option]')].every(o => !o.hidden)"))
key(" "); ok("Space types into search", ev("document.getElementById('search-input').value") == " ")
key("Escape"); ok("first Escape clears text, stays open", ev("document.getElementById('search-input').value") == "" and isopen("search-menu"))
key("End", ctrl=True); ok("Ctrl+End → last option (disabled reachable)", attr("search-input", "aria-activedescendant") == "q-4")
key("Enter"); ok("Enter on disabled ignored", sel("search-list") == "q-2" and isopen("search-menu"))
key("Escape"); ok("second Escape closes, focus trigger", not isopen("search-menu") and H.active() == "search-trigger")
key("Enter"); key("Tab"); ok("Tab from search closes (non-modal)", not isopen("search-menu"))
H.click("#search-trigger"); H.hover("#search-input")
ok("search field focus border (DD-1)", ev("getComputedStyle(document.querySelector('#search-menu .annachy-dropdown-menu__search-field')).borderTopColor") == "rgb(58, 111, 247)")
H.click("#after"); ok("outside click closes search dialog", not isopen("search-menu"))

# ------------------------------------------------ disabled trigger, placement
H.click("#dis-trigger"); ok("disabled trigger cannot open", not isopen("dis-menu"))
ok("disabled trigger not focusable", H.active() != "dis-trigger")
H.click("#bottom-trigger")
ok("flip above when no room (O12)", ev("document.getElementById('bottom-menu').dataset.placement") == "top" and ev("document.getElementById('bottom-menu').getBoundingClientRect().bottom <= document.getElementById('bottom-trigger').getBoundingClientRect().top"))
key("Escape")

# ------------------------------------------------ accessibility tree
H.click("#single-trigger")
get = H.ax()
t = get("#single-trigger"); ok("AX trigger role combobox", t["role"] == "combobox", t); ok("AX trigger name", t["name"] == "Team Product design", t["name"]); ok("AX expanded", t.get("expanded") is True, t)
lb = get("#single-list"); ok("AX listbox name", lb["role"] == "listbox" and lb["name"] == "Team", lb)
o = get("#s-1"); ok("AX option selected", o["role"] == "option" and o["name"] == "Product design" and o.get("selected") is True, o)
d = get("#s-4"); ok("AX disabled option", d.get("disabled") is True and d["name"] == "Finance (unavailable)", d)
key("Escape")
H.click("#multi-trigger"); get = H.ax()
ok("AX listbox multiselectable", get("#multi-list").get("multiselectable") is True, get("#multi-list"))
ok("AX m-3 selected after toggles", get("#m-3").get("selected") is True, get("#m-3"))
ok("AX unselected option exposes selected=false", get("#m-4").get("selected") is False, get("#m-4"))
key("Escape")
H.click("#search-trigger"); get = H.ax()
ok("AX dialog popup", get("#search-menu")["role"] == "dialog" and get("#search-menu")["name"] == "Search team", get("#search-menu"))
s = get("#search-input"); ok("AX search combobox named", s["role"] == "combobox" and s["name"] == "Search", s)
ok("AX status role", get("#search-menu .annachy-dropdown-menu__status")["role"] == "status")
ok("indicator slots aria-hidden", ev("[...document.querySelectorAll('.annachy-dropdown-item__indicator,.annachy-dropdown-menu__search-icon')].every(e => e.getAttribute('aria-hidden') === 'true')"))
key("Escape")
ok("no runtime errors after interaction", not H.problems(), H.problems())
sys.exit(H.finish("R4-1 DROPDOWN CDP"))
