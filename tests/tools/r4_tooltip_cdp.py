"""R4-2 Tooltip — real mouse / keyboard / touch / accessibility audit via CDP. Run from project root."""
import sys, time, os
sys.dont_write_bytecode = True; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cdp_lib import Harness
H = Harness(1400, 900)
ok, ev, key = H.ok, H.ev, H.key
H.navigate("tests/fixtures/r4-tooltip-interaction.html")
ok("loads without errors", not H.problems(), H.problems())
ok("initTooltips exported", ev("import('/src/annachy.js').then(m => typeof m.initTooltips)") == "function")
vis = lambda i: ev(f"!document.getElementById('{i}').hidden")
rect = lambda sel: ev(f"(() => {{ const r = document.querySelector('{sel}').getBoundingClientRect(); return [r.left, r.top, r.right, r.bottom, r.width, r.height]; }})()")
def away(): H.mouse("mouseMoved", 5, 890)
away(); time.sleep(0.3)
ok("all tooltips hidden on load", not any(vis(i) for i in ("tip-top", "tip-left", "tip-icon", "tip-busy", "tip-edge-right", "tip-edge-bottom")))

# ---------------- hover timing (R4-Q4: 500 ms show, 150 ms hide)
H.hover("#t-top"); time.sleep(0.3); ok("hover: not shown before 500 ms", not vis("tip-top"))
time.sleep(0.35); ok("hover: shown after 500 ms", vis("tip-top"))
t, b = rect("#t-top"), rect("#tip-top")
ok("arrow-top → tooltip below trigger, arrow tip touching (gap 12, derived)", abs(b[1] - (t[3] + 12)) < 0.6, (b[1], t[3]))
a = rect("#tip-top .annachy-tooltip__arrow")
ok("arrow centred on trigger", abs((a[0] + a[2]) / 2 - (t[0] + t[2]) / 2) < 0.6, ((a[0] + a[2]) / 2, (t[0] + t[2]) / 2))
away(); time.sleep(0.08); ok("leave: still visible within 150 ms", vis("tip-top"))
time.sleep(0.25); ok("leave: hidden after 150 ms", not vis("tip-top"))
# ---------------- hoverable (WCAG 1.4.13)
H.hover("#t-top"); time.sleep(0.65); ok("shown again", vis("tip-top"))
x, y = H.center("#tip-top"); H.mouse("mouseMoved", x, y); time.sleep(0.4)
ok("pointer moved onto tooltip keeps it open (hoverable)", vis("tip-top"))
away(); time.sleep(0.3); ok("leaving tooltip hides it", not vis("tip-top"))
# ---------------- warm-up / one at a time
H.hover("#t-top"); time.sleep(0.65); H.hover("#t-left"); time.sleep(0.12)
ok("warm-up: next tooltip shows immediately", vis("tip-left"))
ok("one tooltip at a time", not vis("tip-top"))
t, b = rect("#t-left"), rect("#tip-left")
ok("arrow-left → tooltip right of trigger (gap 12)", abs(b[0] - (t[2] + 12)) < 0.6, (b[0], t[2]))
a = rect("#tip-left .annachy-tooltip__arrow")
ok("arrow-left box centre aligned to trigger centre", abs((a[1] + a[3]) / 2 - (t[1] + t[3]) / 2) < 0.6)
away(); time.sleep(0.3)
# ---------------- keyboard focus: immediate, Escape, blur
ev("document.body.focus()")
for _ in range(10):
    key("Tab")
    if H.active() == "t-top": break
ok("keyboard focus shows immediately", vis("tip-top"))
key("Escape"); ok("Escape hides", not vis("tip-top")); ok("Escape keeps focus", H.active() == "t-top")
H.hover("#t-top"); time.sleep(0.65); ok("after Escape, a new hover shows it again (T5)", vis("tip-top")); key("Escape"); away(); time.sleep(0.2)
key("Tab"); ok("Tab to next trigger shows its tooltip", vis("tip-left") and H.active() == "t-left")
key("Tab"); ok("blur hides previous", not vis("tip-left"))
ok("icon-only trigger tooltip shows on focus", vis("tip-icon") and H.active() == "t-icon")
key("Tab"); ok("aria-disabled trigger stays focusable and shows tooltip (T13)", H.active() == "t-busy" and vis("tip-busy"))
key("Tab"); ok("focus leaving hides", not vis("tip-busy"))
# mouse click focus does not keep a :focus-visible tooltip after pointer leaves
H.click("#t-top"); time.sleep(0.65); away(); time.sleep(0.3)
ok("mouse-focused trigger: tooltip stays while focused (persistent)", vis("tip-top"))
H.click("#other"); time.sleep(0.1); ok("clicking elsewhere hides", not vis("tip-top"))
# ---------------- touch (R4-Q5)
H.call("Emulation.setTouchEmulationEnabled", enabled=True, maxTouchPoints=1)
H.tap("#t-left"); time.sleep(0.1); ok("tap focuses trigger and shows tooltip", vis("tip-left"))
H.tap("#other"); time.sleep(0.1); ok("tap outside hides", not vis("tip-left"))
H.call("Emulation.setTouchEmulationEnabled", enabled=False)
# ---------------- collision (T8: only Figma placements)
H.hover("#edge-right"); time.sleep(0.65)
pl = ev("document.getElementById('tip-edge-right').dataset.placement")
r = rect("#tip-edge-right")
ok("right-edge trigger flips to a Figma placement inside the viewport", pl in ("right", "right-center", "top", "top-left", "top-right", "bottom", "bottom-left", "bottom-right") and r[0] >= 0 and r[2] <= 1400, (pl, r))
ok("arrow class follows the placement", ev(f"document.getElementById('tip-edge-right').classList.contains('annachy-tooltip--arrow-{pl}')"))
away(); time.sleep(0.3)
ok("preferred arrow restored after hide", ev("document.getElementById('tip-edge-right').classList.contains('annachy-tooltip--arrow-left')"))
H.hover("#edge-bottom"); time.sleep(0.65)
pl = ev("document.getElementById('tip-edge-bottom').dataset.placement")
ok("bottom-edge trigger (arrow-top) flips to a bottom-arrow placement above", pl.startswith("bottom") and rect("#tip-edge-bottom")[3] <= rect("#edge-bottom")[1], pl)
away(); time.sleep(0.3)
# ---------------- accessibility
get = H.ax()
ok("AX trigger description = tooltip text", get("#t-top")["description"] == "Opens below the trigger", get("#t-top"))
i = get("#t-icon"); ok("AX icon-only: name from aria-label, description from tooltip", i["name"] == "Home" and i["description"] == "Home Go to the start page", i)
ok("tooltip role", ev("[...document.querySelectorAll('.annachy-tooltip')].every(t => t.getAttribute('role') === 'tooltip')"))
ok("tooltip content non-interactive", ev("document.querySelectorAll('.annachy-tooltip a, .annachy-tooltip button, .annachy-tooltip input, .annachy-tooltip [tabindex]').length") == 0)
ok("arrow slots aria-hidden + empty", ev("[...document.querySelectorAll('.annachy-tooltip__arrow')].every(a => a.getAttribute('aria-hidden') === 'true' && !a.childElementCount)"))
ok("no runtime errors", not H.problems(), H.problems())
sys.exit(H.finish("R4-2 TOOLTIP CDP"))
